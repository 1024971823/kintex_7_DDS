#!/usr/bin/env python3
"""Generate quarter-wave sine lookup table ROM for high-SFDR DDS.

Uses 11-bit phase indexing within [0, pi/2) (2048 entries, equivalent to
13-bit full-cycle LUT before linear interpolation) with 18-bit unsigned
amplitude values. Splitting into even/odd banks allows single-cycle access to
adjacent samples y0=LUT[k] and y1=LUT[k+1] for hardware linear interpolation.
"""

import math
from pathlib import Path

ADDR_BITS = 11
N_ENTRIES = 1 << ADDR_BITS  # 2048
AMP_BITS = 18
AMP_MAX = 32767 * 8  # 262136: exact 8x scaling of signed 16-bit full-scale (32767)


def generate_rom_verilog(out_path: Path) -> None:
    half_entries = N_ENTRIES // 2  # 1024 even, 1024 odd
    even_vals = []
    odd_vals = []

    for k in range(N_ENTRIES):
        val = int(round(AMP_MAX * math.sin((math.pi / 2.0) * k / N_ENTRIES)))
        val = min(max(val, 0), AMP_MAX)
        if (k & 1) == 0:
            even_vals.append(val)
        else:
            odd_vals.append(val)

    lines = [
        "`timescale 1ns / 1ps",
        "// Auto-generated by scripts/gen_sin_lut.py -- do not edit manually.",
        "// Quarter-wave sine ROM split into even/odd banks for 1-cycle (y0, y1) fetch.",
        f"// Entries: {N_ENTRIES} (0..pi/2), Amplitude: {AMP_BITS}-bit unsigned [0..{AMP_MAX}].",
        "",
        "module dds_sin_qtr_rom (",
        "    input  wire        clk,",
        "    input  wire [9:0]  addr_even,",
        "    input  wire [9:0]  addr_odd,",
        "    output reg  [17:0] dout_even,",
        "    output reg  [17:0] dout_odd",
        ");",
        "",
        "    (* rom_style = \"block\" *)",
        f"    reg [17:0] rom_even [0:{half_entries - 1}];",
        "    (* rom_style = \"block\" *)",
        f"    reg [17:0] rom_odd  [0:{half_entries - 1}];",
        "",
        "    initial begin",
    ]

    for idx, val in enumerate(even_vals):
        lines.append(f"        rom_even[{idx}] = 18'd{val};")
    for idx, val in enumerate(odd_vals):
        lines.append(f"        rom_odd[{idx}] = 18'd{val};")

    lines.extend([
        "    end",
        "",
        "    always @(posedge clk) begin",
        "        dout_even <= rom_even[addr_even];",
        "        dout_odd  <= rom_odd[addr_odd];",
        "    end",
        "",
        "endmodule",
        "",
    ])

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    target = Path(__file__).resolve().parent.parent / "user" / "src" / "dds_sin_qtr_rom.v"
    generate_rom_verilog(target)
    print(f"Generated {target}")
